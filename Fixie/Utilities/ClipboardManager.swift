import Cocoa

/// How the text Fixie works on is encoded.
enum TextFormat: Equatable {
    /// Plain text, written back as-is.
    case plain
    /// Markdown converted from a rich clipboard (HTML or Slack's Quill delta).
    /// Written back as HTML + plain text so the editor keeps the formatting.
    /// `lineBased` is true for editors where every newline matters (Slack).
    case markdown(lineBased: Bool)
}

/// Manages clipboard operations with save/restore functionality
class ClipboardManager {
    static let shared = ClipboardManager()

    private let pasteboard: NSPasteboard
    /// Every item and every type of the user's clipboard, so images, files
    /// and rich text survive a Fixie round-trip (not just plain strings).
    private var snapshot: [[NSPasteboard.PasteboardType: Data]]?

    /// nspasteboard.org markers: clipboard managers (Raycast, Alfred, Paste…)
    /// skip transient/auto-generated content, so Fixie's temporary writes
    /// don't pollute the user's clipboard history.
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Chromium's custom clipboard data (holds Slack's Quill delta).
    static let chromiumCustomDataType = NSPasteboard.PasteboardType("org.chromium.web-custom-data")

    private init() {
        self.pasteboard = .general
    }

    /// For tests: operate on a private pasteboard.
    init(pasteboard: NSPasteboard) {
        self.pasteboard = pasteboard
    }

    // MARK: - Save / restore

    /// Save the current clipboard content for later restoration
    func saveCurrentContent() {
        snapshot = (pasteboard.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    entry[type] = data
                }
            }
            return entry
        }
    }

    /// Save only if nothing is saved yet (keeps the user's original content
    /// when a capture already replaced the clipboard).
    func saveCurrentContentIfNeeded() {
        if snapshot == nil { saveCurrentContent() }
    }

    var hasSavedContent: Bool { snapshot != nil }

    /// Restore previously saved clipboard content. Does nothing if nothing
    /// was saved — the Accessibility path never touches the clipboard, so it
    /// must not wipe it either.
    func restoreSavedContent() {
        guard let saved = snapshot else { return }
        snapshot = nil
        pasteboard.clearContents()
        let items: [NSPasteboardItem] = saved.compactMap { entry in
            guard !entry.isEmpty else { return nil }
            let item = NSPasteboardItem()
            for (type, data) in entry {
                item.setData(data, forType: type)
            }
            return item
        }
        if !items.isEmpty {
            pasteboard.writeObjects(items)
        }
    }

    // MARK: - Read

    /// Get the current clipboard content
    func getContent() -> String? {
        pasteboard.string(forType: .string)
    }

    /// Get clipboard content, converting rich formats to markdown when they
    /// carry formatting. Electron/web apps (Slite, Slack, Notion…) put HTML
    /// or Slack's Quill delta on the clipboard alongside a lossy plain string.
    func getContentPreferringMarkdown() -> (text: String, format: TextFormat)? {
        // Slack's composer: Quill Delta inside Chromium's web-custom-data
        if let data = pasteboard.data(forType: Self.chromiumCustomDataType),
           let slackJSON = QuillDeltaParser.extractSlackJSON(from: data),
           let markdown = QuillDeltaParser.toMarkdown(slackJSON) {
            return (markdown, .markdown(lineBased: true))
        }

        // HTML → markdown (Slite, Notion, Gmail, Google Docs, rendered Slack messages…)
        if let html = pasteboard.string(forType: .html),
           let result = HTMLToMarkdown.convertDetailed(html),
           result.hasFormatting {
            return (result.markdown, .markdown(lineBased: false))
        }

        // Plain text: the most faithful source when there is no formatting
        // (keeps indentation and spacing that HTML rendering collapses).
        guard let text = pasteboard.string(forType: .string), !text.isEmpty else {
            if let html = pasteboard.string(forType: .html), let result = HTMLToMarkdown.convertDetailed(html) {
                return (result.markdown, .plain)
            }
            return nil
        }
        return (text, .plain)
    }

    // MARK: - Write

    /// Put text on the clipboard in the flavors the target editor needs.
    func setContent(_ text: String, format: TextFormat = .plain) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        switch format {
        case .plain:
            item.setString(text, forType: .string)
        case .markdown(let lineBased):
            item.setString(MarkdownToHTML.html(from: text, preserveBlankLines: lineBased), forType: .html)
            item.setString(MarkdownToHTML.plainText(from: text), forType: .string)
        }
        item.setData(Data(), forType: Self.transientType)
        item.setData(Data(), forType: Self.autoGeneratedType)
        pasteboard.writeObjects([item])
    }

    /// Clear the clipboard
    func clear() {
        pasteboard.clearContents()
    }

    /// Check if clipboard content changed (useful after simulating copy)
    func contentChanged(from original: String?) -> Bool {
        let current = getContent()
        return current != nil && !current!.isEmpty && current != original
    }
}
